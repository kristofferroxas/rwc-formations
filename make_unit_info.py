"""Write formation-plugin/UnitInfo.cs (unit names + footprints for the preview) from
the project's own lookup: files/mechabellum_lookup.py (UNIT_LOOKUP names, dump
footprints), plus the Chinese names (0.9.0): the game's own name_zh from the data
dump (tables reference/units.json), else the developers' unit icon file names
(unit-icons/<id>_<中文>_<English>_Icon_<tier>.png). Hand-run asset prep like files/generate_js_lookup.py; re-run after the
lookup changes (new units, a game patch). Never hand-edit UnitInfo.cs.

    python formation-plugin/make_unit_info.py
"""
import json
import os
import re
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "files"))
import mechabellum_lookup as lookup  # noqa: E402


def title_case(s):
    # Same rule as the site's titleCase (app.js): capitalise each word start.
    return re.sub(r"\b\w", lambda m: m.group(0).upper(), s)


def cs_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


ICON = re.compile(r"^(\d+)_(.+?)_(.+?)_Icon_\d+\.png$")


def chinese_names():
    """unit id -> Chinese name: the game's own name_zh from the data dump
    (tables reference/units.json), else the unit icon file names."""
    out = {}
    folder = os.path.join(HERE, "..", "unit-icons")
    seen = {}
    for f in os.listdir(folder):
        m = ICON.match(f)
        if m:
            seen.setdefault(int(m.group(1)), Counter())[m.group(2)] += 1
    out.update({uid: c.most_common(1)[0][0] for uid, c in seen.items()})
    with open(os.path.join(HERE, "..", "tables reference", "units.json"), encoding="utf-8") as f:
        for u in json.load(f):
            if u.get("name_zh"):
                out[int(u["id"])] = u["name_zh"]
    return out


def main():
    zh = chinese_names()
    rows = []
    for uid in sorted(lookup.UNIT_LOOKUP):
        name = title_case(lookup.UNIT_LOOKUP[uid])
        fp = lookup.unit_footprint(uid)
        w, h = (int(fp[0]), int(fp[1])) if fp else (0, 0)
        zname = cs_string(zh[uid]) if uid in zh else "null"
        rows.append(f"            [{uid}] = ({cs_string(name)}, {w}, {h}, {zname}),")
    out = "\n".join([
        "// GENERATED by formation-plugin/make_unit_info.py from files/mechabellum_lookup.py.",
        "// Do not hand-edit: re-run the script after the lookup changes.",
        "using System.Collections.Generic;",
        "",
        "namespace RwcFormations",
        "{",
        "    internal static class UnitInfo",
        "    {",
        "        // unit id -> (English name, footprint x, footprint y in map units (0 = unknown), Chinese name or null)",
        "        public static readonly Dictionary<int, (string Name, int W, int H, string Zh)> Units = new Dictionary<int, (string, int, int, string)>",
        "        {",
        *rows,
        "        };",
        "",
        "        // The game's Chinese name when the panel is in Chinese, else the English one.",
        '        public static string Name(int id) => !Units.TryGetValue(id, out var u) ? (Tx.Zh ? $"单位 {id}" : $"Unit {id}") : Tx.Zh && u.Zh != null ? u.Zh : u.Name;',
        "    }",
        "}",
        "",
    ])
    path = os.path.join(HERE, "UnitInfo.cs")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print(f"wrote {path}: {len(rows)} units, {sum(1 for u in lookup.UNIT_LOOKUP if u in zh)} with Chinese names")


if __name__ == "__main__":
    main()
