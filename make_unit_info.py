"""Write formation-plugin/UnitInfo.cs (unit names + footprints for the preview) from
the project's own lookup: files/mechabellum_lookup.py (UNIT_LOOKUP names, dump
footprints). Hand-run asset prep like files/generate_js_lookup.py; re-run after the
lookup changes (new units, a game patch). Never hand-edit UnitInfo.cs.

    python formation-plugin/make_unit_info.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "files"))
import mechabellum_lookup as lookup  # noqa: E402


def title_case(s):
    # Same rule as the site's titleCase (app.js): capitalise each word start.
    return re.sub(r"\b\w", lambda m: m.group(0).upper(), s)


def cs_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    rows = []
    for uid in sorted(lookup.UNIT_LOOKUP):
        name = title_case(lookup.UNIT_LOOKUP[uid])
        fp = lookup.unit_footprint(uid)
        w, h = (int(fp[0]), int(fp[1])) if fp else (0, 0)
        rows.append(f"            [{uid}] = ({cs_string(name)}, {w}, {h}),")
    out = "\n".join([
        "// GENERATED by formation-plugin/make_unit_info.py from files/mechabellum_lookup.py.",
        "// Do not hand-edit: re-run the script after the lookup changes.",
        "using System.Collections.Generic;",
        "",
        "namespace RwcFormations",
        "{",
        "    internal static class UnitInfo",
        "    {",
        "        // unit id -> (display name, footprint x, footprint y) in map units (0 = unknown)",
        "        public static readonly Dictionary<int, (string Name, int W, int H)> Units = new Dictionary<int, (string, int, int)>",
        "        {",
        *rows,
        "        };",
        "",
        '        public static string Name(int id) => Units.TryGetValue(id, out var u) ? u.Name : $"Unit {id}";',
        "    }",
        "}",
        "",
    ])
    path = os.path.join(HERE, "UnitInfo.cs")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print(f"wrote {path}: {len(rows)} units")


if __name__ == "__main__":
    main()
